function slugify(value: string): string {
  return (value || '')
    .toLowerCase()
    .replace(/&/g, ' ')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
}

/**
 * Neutral placeholder used when nothing else resolves. A hollow dot reads as
 * "no icon" instead of a heavy filled blob.
 */
const FALLBACK_ICON = 'mdi-circle-small'

/**
 * Convert a stored icon name to an MDI icon name.
 *
 * Accepts Font Awesome ("fa-cog", "cog"), Tabler ("layout-dashboard") and
 * already-MDI ("mdi-cog") names. `name` is the owning category/module/ribbon
 * label, used to pick a sensible icon when nothing is stored at all.
 */
export function faToMdi(faClass: string, name = ''): string {
  const cleaned = (faClass || '')
    // Strip common FA prefixes: "fa-", "fas-", "far-", "fal-", etc.
    .replace(/^fa[srbldk]?-/, '')
    .replace(/^fa /, '')
    // Tabler prefixes
    .replace(/^(ti|tabler)-/, '')
    .trim()
    .toLowerCase()

  // Already an MDI name — pass through untouched.
  if (cleaned.startsWith('mdi-'))
    return cleaned

  const mapped = FA_TO_MDI[cleaned]
  if (mapped)
    return mapped

  return NAME_FALLBACK[slugify(name)] ?? FALLBACK_ICON
}

/**
 * A hub card's icon. Cards are declared in PHP with either a bare MDI name ("account-group") or
 * the Tabler/Font Awesome names the sidebar uses ("building-factory", "search"); the hub page used
 * to prefix "mdi-" onto whatever it was given, so every card declared the second way drew nothing.
 * The sidebar's table first, then the name as an MDI icon.
 */
export function hubCardIcon(icon: string): string {
  const cleaned = (icon || '')
    .replace(/^fa[srbldk]?-/, '')
    .replace(/^fa /, '')
    .replace(/^(ti|tabler)-/, '')
    .trim()
    .toLowerCase()

  if (cleaned.startsWith('mdi-'))
    return cleaned

  return FA_TO_MDI[cleaned] ?? `mdi-${cleaned}`
}
