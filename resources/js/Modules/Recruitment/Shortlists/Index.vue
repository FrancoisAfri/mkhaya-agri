<script setup lang="ts">
import { router } from '@inertiajs/vue3'
import { route as ziggyRoute } from 'ziggy-js'

const route = ziggyRoute

type Shortlist = {
  id: number
  status: string
  status_label: string
  items_count: number
  generated_by: { id: number; name: string } | null
  approved_by: { id: number; name: string } | null
  approved_at: string | null
  created_at: string
}

type Job = {
  id: number
  title: string
}

const props = defineProps<{
  job: Job
  shortlists: Shortlist[]
}>()

const statusColor = (s: string) =>
  s === 'approved' ? 'success' : s === 'pending' ? 'warning' : s === 'rejected' ? 'error' : 'secondary'

function formatDate(val: string | null) {
  if (!val) return '—'
  return new Date(val).toLocaleDateString('en-ZA', { day: '2-digit', month: 'short', year: 'numeric' })
}

const headers = [
  { title: '#',           key: 'id',           sortable: false },
  { title: 'Status',      key: 'status_label', sortable: false },
  { title: 'Candidates',  key: 'items_count',  sortable: false, align: 'end' as const },
  { title: 'Generated By',key: 'generated_by', sortable: false },
  { title: 'Approved By', key: 'approved_by',  sortable: false },
  { title: 'Approved',    key: 'approved_at',  sortable: false },
  { title: 'Created',     key: 'created_at',   sortable: false },
  { title: '',            key: 'actions',      sortable: false, align: 'end' as const },
]
</script>

<template>
  <VContainer fluid class="pa-4 pa-sm-6">
    <div class="d-flex align-center gap-2 mb-6">
      <VBtn icon="tabler-arrow-left" size="small" variant="text" @click="router.visit(route('recruitment.jobs.show', { job: job.id }))" />
      <div>
        <h4 class="text-h4">Shortlists</h4>
        <p class="text-medium-emphasis mb-0">{{ job.title }}</p>
      </div>
    </div>

    <VCard elevation="0" border>
      <VDataTable :headers="headers" :items="shortlists" hover :items-per-page="25">
        <template #item.status_label="{ item }">
          <VChip :color="statusColor(item.status)" size="x-small" variant="tonal">{{ item.status_label }}</VChip>
        </template>
        <template #item.generated_by="{ item }">
          <span class="text-body-2 text-medium-emphasis">{{ item.generated_by?.name ?? '—' }}</span>
        </template>
        <template #item.approved_by="{ item }">
          <span class="text-body-2 text-medium-emphasis">{{ item.approved_by?.name ?? '—' }}</span>
        </template>
        <template #item.approved_at="{ item }">
          <span class="text-body-2 text-medium-emphasis">{{ formatDate(item.approved_at) }}</span>
        </template>
        <template #item.created_at="{ item }">
          <span class="text-body-2 text-medium-emphasis">{{ formatDate(item.created_at) }}</span>
        </template>
        <template #item.actions="{ item }">
          <VBtn
            icon="tabler-eye"
            size="x-small"
            variant="text"
            color="primary"
            @click="router.visit(route('recruitment.shortlists.show', { job: job.id, shortlist: item.id }))"
          />
        </template>
        <template #no-data>
          <div class="text-center pa-10">
            <VIcon icon="tabler-list-check" size="56" color="secondary" class="mb-3" />
            <p class="text-body-1 text-medium-emphasis">No shortlists generated for this job yet.</p>
          </div>
        </template>
      </VDataTable>
    </VCard>
  </VContainer>
</template>
